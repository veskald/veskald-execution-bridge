"""Read/write the .env file that holds the bot's configuration.

Lives in the OS-standard user config dir when frozen (so AppImage and
.app don't try to write into their own read-only bundles), or at the
project root when running from source.
"""
from __future__ import annotations

import os
from pathlib import Path
from typing import Dict

from lib.userdir import app_config_dir


def app_dir() -> Path:
    return app_config_dir()


def env_path() -> Path:
    return app_dir() / ".env"


def read_env() -> Dict[str, str]:
    path = env_path()
    values: Dict[str, str] = {}
    if not path.exists():
        return values
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, _, v = line.partition("=")
        values[k.strip()] = v.strip()
    return values


# Grouped layout so the written file stays readable and matches .env.example.
SECTIONS = [
    ("Veskald", ["HUB_URL", "MACHINE", "UNIQUE_ID"]),
    ("Binance", ["BINANCE_API_KEY", "BINANCE_API_SECRET"]),
    ("Bybit", ["BYBIT_API_KEY", "BYBIT_API_SECRET", "BYBIT_TESTNET"]),
    ("Kraken Futures", ["KRAKEN_API_KEY", "KRAKEN_API_SECRET", "KRAKEN_SANDBOX"]),
    (
        "OKX",
        [
            "OKX_API_KEY",
            "OKX_API_SECRET",
            "OKX_API_PASSPHRASE",
            "OKX_DEMO",
            "OKX_DEFAULT_ISOLATED",
        ],
    ),
    (
        "Coinbase",
        [
            "COINBASE_API_KEY",
            "COINBASE_API_SECRET",
            "COINBASE_INTX_PORTFOLIO_UUID",
        ],
    ),
    (
        "KuCoin Futures",
        [
            "KUCOIN_API_KEY",
            "KUCOIN_API_SECRET",
            "KUCOIN_API_PASSPHRASE",
        ],
    ),
]


def write_env(values: Dict[str, str]) -> Path:
    path = env_path()
    path.parent.mkdir(parents=True, exist_ok=True)

    lines = [
        "# Veskald Execution Bridge configuration",
        "# Generated by the desktop app's Settings dialog.",
        "",
    ]
    written: set[str] = set()
    for label, keys in SECTIONS:
        section_present = any(values.get(k) for k in keys)
        if not section_present:
            continue
        lines.append(f"# {label}")
        for k in keys:
            v = values.get(k)
            if v in (None, ""):
                continue
            lines.append(f"{k}={v}")
            written.add(k)
        lines.append("")

    # Round-trip any unknown keys the user might have added by hand.
    extras = sorted(k for k, v in values.items() if v and k not in written)
    if extras:
        lines.append("# Extra")
        for k in extras:
            lines.append(f"{k}={values[k]}")
        lines.append("")

    path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    try:
        os.chmod(path, 0o600)
    except OSError:
        pass
    return path
